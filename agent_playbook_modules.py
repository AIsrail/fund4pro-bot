def get_module(topic: str) -> str | None:
    """Возвращает текст модуля по ключу, либо None если такого модуля нет."""
    module = PLAYBOOK_MODULES.get(topic)
    return module["content"].strip() if module else None


def module_topics() -> list[str]:
    return list(PLAYBOOK_MODULES.keys())


def module_descriptions_for_tool() -> str:
    """Короткая сводка всех модулей — используется в описании инструмента
    load_playbook_module в agent_tools.py, чтобы модель видела, что где
    искать, не читая содержимое заранее."""
    return "\n".join(f"- {k}: {v['description']}" for k, v in PLAYBOOK_MODULES.items())
