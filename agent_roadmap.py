def build_system_prompt(
    project_data: dict,
    flow: str,
    ui_language: str,
    doc_language: str | None,
    loaded_modules: list[str] | None = None,
) -> str:
    """Собирает системный промпт для текущего хода: неизменная методология
    + ЖИВОЙ снепшот собранных данных проекта (агент видит его целиком на
    каждом ходу, а не только в момент, когда данные были сообщены —
    поэтому не переспрашивает то, что уже знает).

    ЯЗЫК: нет отдельного шага выбора языка общения — агент сам отвечает на
    языке, на котором пишет пользователь (естественное поведение живого
    диалога, не форма). doc_language — язык итогового ДОКУМЕНТА — либо
    определяется автоматически по тексту сайта/формы донора (см.
    agent_engine._execute_tool после fetch_donor_page), либо остаётся тем
    же, что язык общения, если у донора нет текста для анализа.

    loaded_modules — ключи agent_playbook_modules, уже загруженные в этой
    сессии через load_playbook_module (session['loaded_modules']),
    передаются сюда, чтобы модель не пыталась загрузить их повторно."""
    lang_names = {"ru": "русском", "ky": "кыргызском", "en": "английском"}
    subject = "грантового проекта" if flow == "grant" else "бизнес-плана"

    if project_data:
        data_lines = "\n".join(f"- {k}: {v}" for k, v in project_data.items() if v)
    else:
        data_lines = "(пока ничего не собрано — это самое начало разговора)"

    if loaded_modules:
        modules_line = (
            f"\n\nУЖЕ ЗАГРУЖЕНО (не вызывай load_playbook_module с этими "
            f"topic повторно, содержимое уже есть выше в истории диалога): "
            f"{', '.join(loaded_modules)}"
        )
    else:
        modules_line = (
            "\n\nСправочные модули пока не загружались в этом разговоре."
        )

    lang_clause = (
        "\n\nЯЗЫК ОБЩЕНИЯ: отвечай на том языке, на котором пользователь "
        "пишет тебе (определяй по последнему сообщению) — не спрашивай "
        "явно, на каком языке общаться."
    )
    if doc_language:
        lang_clause += (
            f" ГОТОВЫЙ ДОКУМЕНТ (при вызове generate_document) должен быть "
            f"написан на {lang_names.get(doc_language, doc_language)} языке "
            f"— это требование донора (определено по его форме/сайту), "
            f"независимо от языка вашего общения."
        )

    return (
        f"{FULL_ROADMAP_SYSTEM_PROMPT}\n\n"
        f"Сейчас пользователь разрабатывает {subject}.\n\n"
        f"ТЕКУЩИЕ ДАННЫЕ ПРОЕКТА (то, что уже известно — не переспрашивай это):\n"
        f"{data_lines}"
        f"{lang_clause}"
        f"{modules_line}"
    )
