def to_anthropic_tools(openai_tools: list[dict]) -> list[dict]:
    """Anthropic Tool Use использует {name, description, input_schema} на
    верхнем уровне вместо вложенного {type: function, function: {...}}."""
    result = []
    for t in openai_tools:
        fn = t["function"]
        result.append({
            "name": fn["name"],
            "description": fn["description"],
            "input_schema": fn["parameters"],
        })
    return result
